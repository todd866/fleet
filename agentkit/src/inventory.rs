//! Built-in catalogue of operating mechanisms. The public inventory is this
//! text; it does not read the private home directory.

pub fn markdown() -> String {
    let mut out = String::new();
    out.push_str("# Agent operating inventory\n\n");
    out.push_str("Generated by `agentkit inventory`. Edit the catalogue in `agentkit/src/inventory.rs`, then regenerate this file. Site data (hosts, rules, addresses) stays in `~/.config/agentkit`, not here.\n\n");
    out.push_str("Coupling is what is true of the hand-maintained layer today. The neutral home is where agentkit keeps the one copy.\n\n");
    out.push_str("| Mechanism | Today | Coupling | Neutral home |\n");
    out.push_str("|---|---|---|---|\n");
    for row in ROWS {
        out.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            row.mechanism, row.today, row.coupling, row.home
        ));
    }
    out.push_str("\n## Enforcement by provider\n\n");
    out.push_str("| Guard | Claude Code | Codex | Cursor |\n");
    out.push_str("|---|---|---|---|\n");
    out.push_str("| hard-delete | PreToolUse `Bash`, fail closed on a hook crash | `hooks.json` PreToolUse, same decision JSON | `~/.cursor/hooks.json` `beforeShellExecution`, `failClosed: true` |\n");
    out.push_str("| icloud | PreToolUse `Bash` | same | `beforeShellExecution`, `failClosed: true` |\n");
    out.push_str("| offload-heavy | PreToolUse `Bash`, fail open if `offload-target` errors | same, fail open | `beforeShellExecution`, fail open |\n");
    out.push_str("| cd-outside | PreToolUse `Bash` (was inside `no-prompt-patterns.py`) | same | `beforeShellExecution`, `failClosed: true` |\n");
    out.push_str("| push | PreToolUse `Bash`, deny `--force` / `-f`; ask in `push_gate_projects` | same | `beforeShellExecution`, `failClosed: true` |\n");
    out.push_str("\n## Gaps\n\n");
    for gap in GAPS {
        out.push_str(&format!("- **{}** — {} Mitigation: {}\n", gap.provider, gap.gap, gap.mitigation));
    }
    out.push('\n');
    out
}

