use serde_json::Value;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicU64, Ordering};

static N: AtomicU64 = AtomicU64::new(0);

fn bin(name: &str) -> PathBuf {
    PathBuf::from(env(name))
}

fn env(key: &str) -> String {
    match key {
        "agentkit" => env!("CARGO_BIN_EXE_agentkit").to_string(),
        "guard-hard-delete" => env!("CARGO_BIN_EXE_guard-hard-delete").to_string(),
        "agent-context" => env!("CARGO_BIN_EXE_agent-context").to_string(),
        other => panic!("unknown bin {other}"),
    }
}

struct Home {
    root: PathBuf,
}

impl Home {
    fn new() -> Self {
        let n = N.fetch_add(1, Ordering::Relaxed);
        let root = std::env::temp_dir().join(format!("agentkit-test-{}-{n}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(root.join(".config/agentkit")).unwrap();
        fs::create_dir_all(root.join(".local/bin")).unwrap();
        // The hook programs where the generated hooks look for them.
        std::os::unix::fs::symlink(bin("agentkit"), root.join(".local/bin/agentkit")).unwrap();
        std::os::unix::fs::symlink(bin("agent-context"), root.join(".local/bin/agent-context")).unwrap();
        fs::create_dir_all(root.join(".local/state")).unwrap();
        fs::create_dir_all(root.join(".codex")).unwrap();
        let mut codex_cfg = String::new();
        codex_cfg.push_str(
            "[hooks.state.\"pre_tool_use:0:0\"]\ntrusted_hash = \"sha256:test0\"\n\n",
        );
        fs::write(root.join(".codex/config.toml"), codex_cfg).unwrap();
        Self { root }
    }
    fn config(&self) -> PathBuf {
        self.root.join(".config/agentkit")
    }
    fn write(&self, rel: &str, body: &str) {
        let path = self.config().join(rel);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, body).unwrap();
    }
    fn site(&self) {
        self.write(
            "agentkit.toml",
            "schema = 1\nmanage_model = false\n\n[[projects]]\nname = \"example\"\npath = \"work/example\"\n",
        );
        self.write("rules/core-always.md", "Use the Trash.\n");
        self.write("rules/appendix-claude.md", "\n");
        self.write("rules/appendix-codex.md", "\n");
        self.write("rules/appendix-cursor.md", "\n");
        self.write("rules/projects/example.md", "# Example\n\nKeep the gate green.\n");
        self.write(
            "skills/sample/SKILL.md",
            "---\nname: sample\ndescription: Sample skill for the round trip.\n---\n\nDo the sample thing.\n",
        );
        self.write("memory/INDEX.md", "# Memory index\n\n");
    }
    fn run(&self, args: &[&str]) -> (i32, String, String) {
        // Placed by a flag: agentkit takes no path from the environment. The config and state
        // folders follow the home.
        let out = Command::new(bin("agentkit"))
            .args(args)
            .arg("--home")
            .arg(&self.root)
            .env("HOME", &self.root)
            .env("AGENTKIT_SKIP_SSH_RESOLVE", "1")
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .output()
            .unwrap();
        (
            out.status.code().unwrap_or(1),
            String::from_utf8_lossy(&out.stdout).into_owned(),
            String::from_utf8_lossy(&out.stderr).into_owned(),
        )
    }
}

impl Drop for Home {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

#[test]
fn sync_is_idempotent_and_doctor_sees_drift() {
    let home = Home::new();
    home.site();
    let (code, dry, err) = home.run(&["sync"]);
    assert_eq!(code, 0, "{err}");
    assert!(dry.contains("would change"), "{dry}");
    assert!(dry.contains("Use the Trash"), "{dry}");
    let (code, applied, err) = home.run(&["sync", "--apply"]);
    assert_eq!(code, 0, "{err}{applied}");
    assert!(applied.contains("applied"), "{applied}");
    assert!(home.root.join(".local/state/agentkit/backups").exists() || applied.contains("applied"));
    let claude = fs::read_to_string(home.root.join(".claude/CLAUDE.md")).unwrap();
    assert!(claude.contains("generated by agentkit"));
    assert!(claude.contains("Use the Trash"));
    assert!(claude.contains("edit the source"));
    for rule in ["hard-delete:", "icloud:", "offload-heavy:", "cd-outside:", "push:"] {
        assert!(claude.contains(rule), "global rules omit {rule}\n{claude}");
    }
    let agents = fs::read_to_string(home.root.join(".codex/AGENTS.md")).unwrap();
    assert!(agents.contains("Use the Trash"));
    assert!(agents.contains("hard-delete:"), "{agents}");
    let project_agents = fs::read_to_string(home.root.join("work/example/AGENTS.md")).unwrap();
    assert!(project_agents.contains("Keep the gate green"));
    let project_claude = fs::read_to_string(home.root.join("work/example/CLAUDE.md")).unwrap();
    assert!(project_claude.contains("@AGENTS.md"));
    assert!(!project_claude.contains("Keep the gate green"));
    let rule = fs::read_to_string(home.root.join(".cursor/rules/agentkit-global.mdc")).unwrap();
    assert!(rule.contains("alwaysApply: true"));
    assert!(rule.contains("Use the Trash"));
    assert!(rule.contains("hard-delete:"), "{rule}");
    assert!(rule.contains("icloud:"), "{rule}");
    let skill = fs::read_to_string(home.root.join(".claude/skills/sample/SKILL.md")).unwrap();
    assert!(skill.contains("generated by agentkit"));
    assert!(skill.contains("Do the sample thing."));
    assert!(!skill.contains("agentkit:guards"), "a skill is not a second copy of the guards\n{skill}");
    assert!(home.root.join(".codex/skills/sample/SKILL.md").is_file());
    assert!(home.root.join(".cursor/rules/skill-sample.mdc").is_file());
    assert!(home.root.join(".cursor/commands/sample.md").is_file());
    let hooks = fs::read_to_string(home.root.join(".cursor/hooks.json")).unwrap();
    assert!(hooks.contains("hook cursor all"), "{hooks}");
    assert!(!hooks.contains("hook cursor hard-delete"), "expected one combined hook\n{hooks}");
    assert!(hooks.contains("agent-context"));
    assert!(hooks.contains("\"failClosed\": true"));
    let (code, again, err) = home.run(&["sync"]);
    assert_eq!(code, 0, "{err}");
    assert!(again.contains("no changes"), "{again}");
    let (code, doc, err) = home.run(&["doctor"]);
    assert_eq!(code, 0, "{err}{doc}");
    assert!(doc.contains("* cursor"), "{doc}");
    assert!(doc.contains("* claude"), "{doc}");
    assert!(doc.contains("* codex"), "{doc}");
    let report: Value = serde_json::from_str(
        &fs::read_to_string(home.root.join(".local/state/agentkit/doctor.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(report["ok"], true);
    fs::write(home.root.join(".cursor/rules/agentkit-global.mdc"), "drift\n").unwrap();
    let (code, doc, err) = home.run(&["doctor", "--provider", "cursor"]);
    assert_eq!(code, 1, "{err}{doc}");
    assert!(doc.starts_with('!'), "{doc}");
    let report: Value = serde_json::from_str(
        &fs::read_to_string(home.root.join(".local/state/agentkit/doctor.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(report["ok"], false);
    assert!(!report["issues"].as_array().unwrap().is_empty());
}

