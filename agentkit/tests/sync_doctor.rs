fn guard_binary_relative_delete_follows_claude_project_dir() {
    use std::io::Write;
    let home = Home::new();
    let decision = |dir: &str| {
        let mut child = Command::new(bin("guard-hard-delete"))
            .arg("--home")
            .arg(&home.root)
            .env("HOME", &home.root)
            .env("CLAUDE_PROJECT_DIR", dir)
            .env("AGENTKIT_SKIP_SSH_RESOLVE", "1")
            .current_dir("/tmp")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .unwrap();
        child
            .stdin
            .as_mut()
            .unwrap()
            .write_all(br#"{"tool_name":"Bash","tool_input":{"command":"rm notes.txt"}}"#)
            .unwrap();
        let out = child.wait_with_output().unwrap();
        let v: Value = serde_json::from_slice(&out.stdout).unwrap_or_else(|_| {
            panic!(
                "stdout {} stderr {}",
                String::from_utf8_lossy(&out.stdout),
                String::from_utf8_lossy(&out.stderr)
            )
        });
        v["decision"].as_str().unwrap_or("").to_string()
    };
    assert_eq!(decision("/var/agentkit-self-test/project"), "deny");
    assert_eq!(decision("/tmp/agentkit-job"), "allow");
}

